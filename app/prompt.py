def build_user_message(product, gaps: list) -> str:
    """Входные данные для модели: ровно то, что пришло, плюс список пробелов."""
    payload = {
        "name": product.name,
        "manufacturer": product.manufacturer or "данных нет",
        "specs": product.specs or {},
        "description": product.description or "данных нет",
    }
    lines = [
        "Входные данные о приборе (единственный допустимый источник технических значений):",
        json.dumps(payload, ensure_ascii=False, indent=2),
    ]
    if gaps:
        lines += [
            "",
            "Во входных данных нет этих полей - не придумывай их, верни их в missing_data "
            "и в specs со значением «данных нет»:",
            "; ".join(gaps),
        ]
    lines += ["", "Собери черновик карточки товара в описанном JSON-формате."]
    return "\n".join(lines)


def build_length_fix(problems: list, previous: str) -> str:
    """Просьба переписать ответ, когда не сошлись длины."""
    return (
        "Предыдущий ответ не прошёл проверку длин:\n- "
        + "\n- ".join(problems)
        + "\n\nПерепиши JSON целиком, сохранив все значения характеристик без изменений, "
        "и приведи длины к требованиям. Не добавляй новых технических значений: только "
        "расширяй или сокращай описание назначения и применения.\n\n"
        "Предыдущий ответ:\n" + previous
    )
